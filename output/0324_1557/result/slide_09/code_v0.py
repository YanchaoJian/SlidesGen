import os
from pptx import Presentation
from pptx.util import Inches, Pt
from pptx.dml.color import RGBColor
from pptx.enum.text import PP_ALIGN, MSO_AUTO_SIZE
from pptx.enum.shapes import MSO_SHAPE
from pptx.enum.dml import MSO_LINE_DASH_STYLE

def add_slide(prs):
    # Add a blank slide
    slide = prs.slides.add_slide(prs.slide_layouts[6])  # Blank layout

    # [1. Global Settings] Set background color to light gray
    slide_background = slide.shapes.add_shape(
        MSO_SHAPE.RECTANGLE, Inches(0), Inches(0), Inches(10), Inches(5.625)
    )
    slide_background.fill.solid()
    slide_background.fill.fore_color.rgb = RGBColor(245, 245, 245)
    slide_background.line.color.rgb = RGBColor(245, 245, 245)  # Remove border

    # [2. Static Decoration Layer]
    # Top title area with deep blue background
    title_area = slide.shapes.add_shape(
        MSO_SHAPE.RECTANGLE, Inches(0), Inches(0), Inches(10), Inches(1.125)
    )
    title_area.fill.solid()
    title_area.fill.fore_color.rgb = RGBColor(0, 63, 135)
    title_area.line.color.rgb = RGBColor(0, 63, 135)  # Remove border

    # Thin horizontal line below the title area
    separator_line = slide.shapes.add_shape(
        MSO_SHAPE.RECTANGLE, Inches(0), Inches(1.125), Inches(10), Inches(0.02)
    )
    separator_line.fill.solid()
    separator_line.fill.fore_color.rgb = RGBColor(0, 63, 135)
    separator_line.line.color.rgb = RGBColor(0, 63, 135)  # Remove border

    # Bottom area with light gray background
    footer_area = slide.shapes.add_shape(
        MSO_SHAPE.RECTANGLE, Inches(0), Inches(5.625 - 1.125), Inches(10), Inches(1.125)
    )
    footer_area.fill.solid()
    footer_area.fill.fore_color.rgb = RGBColor(245, 245, 245)
    footer_area.line.color.rgb = RGBColor(245, 245, 245)  # Remove border

    # Footer text
    footer_text_box = footer_area.text_frame
    footer_text_box.text = "Generated by Python-pptx"
    footer_text_box.paragraphs[0].font.size = Pt(12)
    footer_text_box.paragraphs[0].font.color.rgb = RGBColor(51, 51, 51)
    footer_text_box.paragraphs[0].alignment = PP_ALIGN.RIGHT

    # [3. Dynamic Layout Layer]
    # Title
    title_text_box = slide.shapes.add_textbox(
        Inches(0), Inches(0.5), Inches(10), Inches(1.125)
    )
    title_text_frame = title_text_box.text_frame
    title_text_frame.text = "Conclusion: Impact and Future Directions"
    title_paragraph = title_text_frame.paragraphs[0]
    title_paragraph.font.size = Pt(32)
    title_paragraph.font.bold = True
    title_paragraph.font.color.rgb = RGBColor(255, 255, 255)
    title_paragraph.font.name = "Microsoft YaHei"
    title_paragraph.alignment = PP_ALIGN.CENTER

    # Bullet points
    bullet_text_box = slide.shapes.add_textbox(
        Inches(0.5), Inches(1.5), Inches(9), Inches(3.375)
    )
    bullet_text_frame = bullet_text_box.text_frame
    bullet_text_frame.word_wrap = True
    bullet_text_frame.auto_size = MSO_AUTO_SIZE.TEXT_TO_FIT_SHAPE

    bullet_points = [
        "The Transformer sets a new benchmark for sequence transduction models, offering faster training and improved performance.",
        "Future work includes extending the model to other modalities like images and audio.",
        "Exploring restricted attention mechanisms for large inputs is another promising direction.",
    ]

    for point in bullet_points:
        p = bullet_text_frame.add_paragraph()
        p.text = point
        p.font.size = Pt(18)
        p.font.color.rgb = RGBColor(51, 51, 51)
        p.font.name = "Microsoft YaHei"
        p.level = 0  # Bullet level 0

    # [4. Notes]
    slide.notes_slide.notes_text_frame.text = (
        "Summarize the impact of the Transformer and outline potential future research directions."
    )

if __name__ == "__main__":
    output_pptx_path = "output/0324_1557/result/slide_09/slide.pptx"
    prs = Presentation()
    prs.slide_width = Inches(10)
    prs.slide_height = Inches(5.625)
    add_slide(prs)
    os.makedirs(os.path.dirname(output_pptx_path), exist_ok=True)
    prs.save(output_pptx_path)